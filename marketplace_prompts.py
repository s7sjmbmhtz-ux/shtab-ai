CATEGORY_TITLES = {"other": "Товар"}


def build_prompts(
    kind: str,
    product: str,
    features: str,
    style: str,
    goal: str,
    platform: str,
    category: str,
    *,
    has_photo: bool,
) -> list[str]:
    features = features.strip()
    features_block = (
        f"Характеристики, указанные пользователем: {features}. "
        if features
        else
        "Дополнительные характеристики пользователем не указаны. Ничего не придумывай. "
    )
    source_block = (
        "Используй загруженную фотографию как обязательный источник внешнего вида товара. "
        "Сохрани форму, пропорции, конструкцию, материал, цвет и видимые детали товара. "
        if has_photo
        else
        "Создай изображение строго по названию и данным пользователя. "
    )
    base = (
        "Создай профессиональное товарное изображение для маркетплейса. "
        f"Товар: {product}. "
        f"{features_block}"
        f"{source_block}"
        "Не добавляй свойства, преимущества, комплектацию, размеры, назначение или детали, "
        "которых нет на фото или в данных пользователя. "
        "Не заменяй товар другим объектом. "
        f"{PLATFORM.get(platform, PLATFORM['all'])}. "
        f"Стиль: {STYLE.get(style, STYLE['minimal'])}. "
        "Вертикальная композиция 4:5. "
        "Без текста, логотипов, случайных букв, ценников и водяных знаков. "
    )
    if kind == "main":
        return [base + "Главное фото: товар полностью виден, расположен по центру, чистый фон."]
    if kind == "lifestyle":
        return [base + "Lifestyle-сцена: естественный контекст использования, сам товар не менять."]
    if kind == "infographic":
        return [base + "Основа инфографики: оставить чистые пустые зоны, текст не генерировать."]
    return [
        base + "Карточка 1 — главное фото: товар по центру, чистый фон.",
        base + "Карточка 2 — lifestyle: естественный контекст использования.",
        base + "Карточка 3 — детали: крупный план только реальных видимых деталей.",
    ]
